test('settings validation, discard navigation, secret reveal and mobile accessibility',async({page})=>{
 await page.getByRole('link',{name:'设置',exact:true}).click()
 await page.getByLabel('Web 端口',{exact:true}).fill('80')
 await page.getByRole('button',{name:'保存设置',exact:true}).click()
 await expect(page.locator('#webPort-help')).toContainText('1024')
 await expect(page.locator('#webPort')).toBeFocused()
 await page.getByRole('link',{name:'概览',exact:true}).click()
 await expect(page.getByRole('dialog')).toBeVisible()
 await page.getByRole('dialog').getByRole('button',{name:'放弃修改',exact:true}).click()
 await expect(page.getByRole('heading',{name:'概览',exact:true})).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.getByRole('link',{name:'设置',exact:true}).click()
 await page.getByRole('button',{name:'修改管理员密码',exact:true}).click()
 await page.getByLabel('当前密码',{exact:true}).fill('secret')
 await page.getByRole('button',{name:'显示当前密码',exact:true}).click()
 await expect(page.locator('#currentPassword')).toHaveAttribute('type','text')
 await page.getByRole('button',{name:'隐藏当前密码',exact:true}).click()
 await expect(page.locator('#currentPassword')).toHaveAttribute('type','password')
 await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
 const a11y=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()
 expect(a11y.violations).toEqual([])
 await page.emulateMedia({reducedMotion:'reduce'})
 const scroll=await page.evaluate(()=>getComputedStyle(document.documentElement).scrollbarColor)
 expect(scroll).not.toBe('auto')
 await page.screenshot({path:'../build/ui-mobile.png',fullPage:true})
})
